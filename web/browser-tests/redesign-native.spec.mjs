import { test, expect } from '@playwright/test';
import { readFile, writeFile, rename } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import AxeBuilder from '@axe-core/playwright';

const directory = resolve('../.artifacts/ui-redesign-20261009/native');
test('actual collected connection gauge reaches the rendered Fleet through the production API', async ({ page }) => {
  const binding = JSON.parse(await readFile(resolve(directory, 'binding.json'), 'utf8'));
  const manifest = await readFile(resolve('dist/.vite/manifest.json'));
  expect(createHash('sha256').update(manifest).digest('hex')).toBe(binding.dashboardManifestSha256);
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(request.url()); });
  const response = page.waitForResponse(value => new URL(value.url()).pathname === '/api/v1/overview');
  await page.goto('/#/overview?' + new URLSearchParams({ target: binding.targetId, range: 'custom', from: binding.fromUtc, to: binding.toUtc }));
  const overview = await response; expect(overview.status()).toBe(200);
  const evidence = (await overview.json()).evidence;
  expect(evidence).toHaveLength(1); expect(evidence[0].targetId).toBe(binding.targetId);
  const gauge = evidence[0].series.find(row => row.metric === 'engine.user_connections');
  expect(gauge.points).toHaveLength(1); expect(gauge.points[0].value).toBe(binding.connections);
  await expect(page.getByRole('heading', { name: 'Server fleet', exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Workload breakdown', exact: true }).selectOption('server');
  await page.getByRole('combobox', { name: 'Workload metric', exact: true }).selectOption('engine.user_connections');
  await page.locator('.primary-overview-charts .chart-values').first().getByText('View chart values', { exact: true }).click();
  const row = page.getByRole('region', { name: 'Chart observation values', exact: true }).locator('tbody tr');
  await expect(row).toHaveCount(1);
  await expect(row).toContainText(binding.connections.toLocaleString('en-US'));
  await expect(row).toContainText('LOCAL NATIVE SQL LAB');
  await expect(page.getByRole('button', { name: 'Save investigation', exact: true })).toHaveCount(0);
  expect(requests.some(url => /\/query$|\/query-text|\/content\//.test(new URL(url).pathname))).toBe(false);
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(axe.violations.map(item => item.id)).toEqual([]);
  await page.screenshot({ path: resolve(directory, 'fleet-native.png'), fullPage: true });
  expect(errors).toEqual([]);
  const receipt = { runId: binding.runId, targetId: binding.targetId, connections: binding.connections, rendered: true, apiStatus: overview.status(), browser: 'chromium', dashboardManifestSha256: binding.dashboardManifestSha256, qualification: binding.qualification };
  const temporary = binding.receiptPath + '.tmp';
  await writeFile(temporary, JSON.stringify(receipt, null, 2)); await rename(temporary, binding.receiptPath);
});
